/** Decodes a mask into a row-major array of 0 (water) and 1 (land). */
export function decodeMask(mask: Mask = MASK): Uint8Array {
  const out = new Uint8Array(mask.cols * mask.rows);
  mask.rle.forEach((row, r) => {
    let c = 0;
    let land = 0;
    for (let i = 0; i < row.length; i += 2) {
      const n = parseInt(row.slice(i, i + 2), 36);
      if (land) out.fill(1, r * mask.cols + c, r * mask.cols + c + n);
      c += n;
      land ^= 1;
    }
  });
  return out;
}

/**
 * Maps a 0–1 position on a whole-world equirectangular map (x from -180°, y
 * from +90°) to fractional cell coordinates inside a crop.
 */
export function toCell(x: number, y: number, mask: Mask = MASK) {
  const lon = x * 360 - 180;
  const lat = 90 - y * 180;
  return {
    lon,
    lat,
    col: ((lon - mask.west) / (mask.east - mask.west)) * mask.cols,
    row: ((mask.north - lat) / (mask.north - mask.south)) * mask.rows,
  };
}
