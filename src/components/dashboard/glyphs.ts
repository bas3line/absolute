/* Plans, 24 × 5: the front of a 1U unit, one lit LED per core. ---------------- */

// '#' the faceplate, 'o' a core's LED, 'v' vents, 'l' the Blackbox's lock light.
export function rackUnit(cores: number, blackbox: boolean): Rows {
  const leds = "o".repeat(Math.min(10, cores)).padEnd(10, ".");
  const vents = "v.v.v.v.";
  return [
    "########################",
    "#......................#",
    `#.${leds}.${vents}${blackbox ? "l" : "."}.#`,
    "#......................#",
    "########################",
  ];
}

